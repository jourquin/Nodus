package edu.uclouvain.core.nodus.database;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.junit.jupiter.api.DynamicTest.dynamicTest;

import java.nio.file.Path;
import java.sql.Connection;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;
import org.junit.jupiter.api.DynamicTest;
import org.junit.jupiter.api.TestFactory;
import org.junit.jupiter.api.io.TempDir;
import org.junit.jupiter.api.parallel.ResourceLock;

/** Metadata that cannot be copied must never disappear through schema replacement. */
@ResourceLock("JDBCUtils")
public class TableDefinitionGuardTest {
  @TempDir Path directory;

  @TestFactory
  List<DynamicTest> replacementsRefuseProtectedDefinitionsBeforeLoading() {
    List<DynamicTest> tests = new ArrayList<>();
    for (boolean hsql : new boolean[] {false, true}) {
      for (String kind :
          List.of(
              "plain",
              "index",
              "primary",
              "check",
              "notnull",
              "default",
              "identity",
              "generated",
              "foreign",
              "trigger",
              "grant",
              "columnGrant")) {
        if (!hsql && kind.equals("columnGrant")) {
          continue;
        }
        tests.add(
            dynamicTest(
                hsql + "/" + kind,
                () -> {
                  try (DatabaseFixture db = new DatabaseFixture(directory, hsql)) {
                    String columns =
                        kind.equals("primary")
                            ? "id INTEGER PRIMARY KEY,label VARCHAR(16)"
                            : kind.equals("notnull")
                                ? "id INTEGER NOT NULL,label VARCHAR(16)"
                                : kind.equals("default")
                                    ? "id INTEGER DEFAULT 9,label VARCHAR(16)"
                                    : kind.equals("identity")
                                        ? "id INTEGER GENERATED BY DEFAULT AS IDENTITY,"
                                            + "label VARCHAR(16)"
                                        : kind.equals("generated")
                                            ? "id INTEGER,label INTEGER GENERATED ALWAYS AS (id*2)"
                                            : kind.equals("check")
                                                ? "id INTEGER CHECK(id>0),label VARCHAR(16)"
                                                : "id INTEGER,label VARCHAR(16)";
                    db.execute("CREATE TABLE data(" + columns + ")");
                    if (kind.equals("generated")) {
                      db.execute("INSERT INTO data(id) VALUES(99)");
                    } else {
                      db.execute("INSERT INTO data VALUES(99,'original')");
                    }
                    if (kind.equals("index")) {
                      db.execute("CREATE INDEX guard_index ON data(label)");
                    } else if (kind.equals("foreign")) {
                      db.execute("CREATE TABLE parent(id INTEGER PRIMARY KEY)");
                      db.execute("INSERT INTO parent VALUES(99)");
                      db.execute(
                          "ALTER TABLE data ADD CONSTRAINT guard_fk FOREIGN KEY(id)"
                              + " REFERENCES parent(id)");
                    } else if (kind.equals("trigger")) {
                      if (hsql) {
                        db.execute("CREATE TABLE audit(id INTEGER)");
                        db.execute(
                            "CREATE TRIGGER guard_trigger AFTER INSERT ON data"
                                + " REFERENCING NEW ROW AS n "
                                + "FOR EACH ROW INSERT INTO audit VALUES(n.id)");
                      } else {
                        db.execute(
                            "CREATE TRIGGER guard_trigger BEFORE INSERT ON data"
                                + " FOR EACH ROW CALL \""
                                + TableDefinitionGuardTest.class.getName()
                                + "$KeepTrigger\"");
                      }
                    } else if (kind.equals("grant") || kind.equals("columnGrant")) {
                      db.execute("CREATE USER other PASSWORD ''");
                      db.execute(
                          "GRANT SELECT"
                              + (kind.equals("columnGrant") ? "(label)" : "")
                              + " ON data TO other");
                    }
                    boolean[] loaded = {false};
                    TableImport.Loader loader =
                        (connection, staged) -> {
                          loaded[0] = true;
                          try (Statement s = connection.createStatement()) {
                            s.execute("CREATE TABLE " + staged + "(id INTEGER,label VARCHAR(16))");
                            s.execute("INSERT INTO " + staged + " VALUES(1,'new')");
                          }
                        };
                    if (kind.equals("plain")) {
                      TableImport.replace(db.project, "data", loader);
                      assertTrue(loaded[0]);
                    } else {
                      SQLException error =
                          assertThrows(
                              SQLException.class,
                              () -> TableImport.replace(db.project, "data", loader));
                      assertTrue(
                          error.getMessage().contains("Cannot replace table"), error.getMessage());
                      assertFalse(
                          loaded[0], "Definition must be inspected before loading the source");
                      try (Statement s = db.connection.createStatement();
                          ResultSet rows = s.executeQuery("SELECT id FROM data")) {
                        assertTrue(rows.next());
                        assertEquals(99, rows.getInt(1));
                        assertFalse(rows.next());
                      }
                    }
                  }
                }));
      }
    }
    return tests;
  }

  @TestFactory
  List<DynamicTest> cancellationAndLateGrantsPreventPublicationAfterRowsAreLoaded() {
    List<DynamicTest> tests = new ArrayList<>();
    for (boolean hsql : new boolean[] {false, true}) {
      for (boolean cancel : new boolean[] {false, true}) {
        tests.add(
            dynamicTest(
                hsql + "/cancel=" + cancel,
                () -> {
                  try (DatabaseFixture db = new DatabaseFixture(directory, hsql)) {
                    db.execute("CREATE TABLE data(id INTEGER,label VARCHAR(16))");
                    db.execute("INSERT INTO data VALUES(99,'original')");
                    db.execute("CREATE USER other PASSWORD ''");
                    ImportProgress progress = new ImportProgress();
                    SQLException error =
                        assertThrows(
                            SQLException.class,
                            () ->
                                TableImport.replace(
                                    db.project,
                                    "data",
                                    (connection, staged) -> {
                                      try (Statement s = connection.createStatement()) {
                                        s.execute(
                                            "CREATE TABLE "
                                                + staged
                                                + "(id INTEGER,label VARCHAR(16))");
                                        s.execute("INSERT INTO " + staged + " VALUES(1,'loaded')");
                                      }
                                      if (cancel) {
                                        assertTrue(progress.cancel());
                                      } else {
                                        db.execute("GRANT SELECT ON data TO other");
                                      }
                                    },
                                    progress));
                    assertTrue(
                        error.getMessage().contains(cancel ? "cancelled" : "Cannot replace table"),
                        error.getMessage());
                    try (Statement s = db.connection.createStatement();
                        ResultSet rows = s.executeQuery("SELECT id FROM data")) {
                      assertTrue(rows.next());
                      assertEquals(99, rows.getInt(1));
                      assertFalse(rows.next());
                    }
                  }
                }));
      }
    }
    return tests;
  }

  /** Inert H2 trigger used to verify metadata protection without an external dependency. */
  public static final class KeepTrigger implements org.h2.api.Trigger {
    /** Default constructor required by H2. */
    public KeepTrigger() {}

    @Override
    public void fire(Connection connection, Object[] oldRow, Object[] newRow) {}
  }
}
